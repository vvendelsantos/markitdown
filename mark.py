def endereco_publico(link: str) -> bool:
    """Aceita apenas endereços HTTP(S) para fotos publicadas na internet."""
    try:
        url = urlparse(link)
        return url.scheme in ("http", "https") and bool(url.netloc)
    except ValueError:
        return False


